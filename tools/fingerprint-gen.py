#!/usr/bin/env python3
"""Generate src/fingerprint.js: original fingerprint artwork for the "NEU" mark.

The ridges are contour lines of a synthetic whorl-shaped scalar field, cut into
segments with random gaps and given slightly uneven ink (opacity and width).
Nothing is traced from a real fingerprint or an existing image.

Deterministic for a given numpy/matplotlib version: fixed seeds below.
Usage: python3 tools/fingerprint-gen.py > src/fingerprint.js
"""
import random

import matplotlib
import numpy as np

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

SEED = 3
INK_SEED = 11
W, H = 100, 124


def ridges():
    random.seed(SEED)
    np.random.seed(SEED)
    x = np.linspace(0, W, 400)
    y = np.linspace(0, H, 500)
    X, Y = np.meshgrid(x, y)
    cx, cy = 48, 54
    dx = (X - cx) / 0.8
    dy = Y - cy
    r = np.sqrt(dx**2 + dy**2)
    th = np.arctan2(dy, dx)
    # Lower ridges flatten toward the crease, like a real finger
    low = np.clip((Y - cy - 20) / 45, 0, 1) ** 1.5
    f = r * (1 - 0.35 * low) + low * (Y - cy) * 0.5
    f += 1.8 * np.sin(2 * th + 0.6) * np.exp(-r / 18) + 0.6 * np.sin(X / 7 + Y / 11)
    mask = ((X - 50) / 42) ** 2 + ((Y - 60) / 54) ** 2 <= 1
    f = np.where(mask, f, np.nan)
    cs = plt.contour(X, Y, f, levels=np.arange(1.5, 70, 2.35))
    out = []
    for seg_list in cs.allsegs:
        for seg in seg_list:
            if len(seg) < 6:
                continue
            cur = []
            for p in seg[::5]:
                # Random ridge breaks
                if random.random() < 0.025 and len(cur) > 4:
                    out.append(cur)
                    cur = []
                    continue
                cur.append(p)
            if len(cur) > 4:
                out.append(cur)
    return out


def main():
    paths = ridges()
    random.seed(INK_SEED)
    rows = []
    for p in paths:
        pts = [(round(a * 2) / 2, round(b * 2) / 2) for a, b in p]
        d = "M" + " ".join(f"{a:g} {b:g}" for a, b in pts)
        opacity = random.choice([0.6, 0.75, 0.9, 1])
        width = random.choice([1.0, 1.15, 1.3])
        rows.append(f"  ['{d}', {opacity:g}, {width:g}],")
    print("// Generated by tools/fingerprint-gen.py. Do not edit by hand.")
    print("// Original artwork: contour lines of a synthetic whorl field, not traced")
    print("// from a real fingerprint. Each entry: [path data, stroke opacity, stroke width].")
    print("// viewBox 0 0 100 124.")
    print("export const FINGERPRINT_VIEWBOX = '0 0 100 124';")
    print("export const FINGERPRINT_RIDGES = Object.freeze([")
    print("\n".join(rows))
    print("].map((r) => Object.freeze(r)));")


if __name__ == "__main__":
    main()
